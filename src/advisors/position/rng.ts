/**
 * Управляемая случайность для сравнения расстановок.
 *
 * Зачем это нужно. Симулятор оценивает расстановку методом Монте-Карло, и при
 * 300 симуляциях стандартная ошибка доли около 3 п.п. Разница между хорошей
 * и отличной расстановкой часто 1–3 п.п. Если оценить тысячи кандидатов
 * независимыми прогонами и взять максимум, победит не лучшая расстановка,
 * а самая удачливая: максимум из тысячи зашумлённых оценок смещён вверх на
 * несколько стандартных ошибок, и смещение это больше самого сигнала.
 *
 * Лекарство напрашивалось такое: общие случайные числа, когда все кандидаты
 * играются против одной последовательности случайностей. Замер показал, что
 * оно не работает (docs/position.md), и зерно осталось здесь ради другого —
 * воспроизводимости разбора: один и тот же вход обязан давать один и тот же
 * ответ, иначе спорный совет нечем изучить.
 */

import { createSeededRng, withRng } from '@firestone-hs/simulate-bgs-battle';

export type Random = () => number;

/**
 * mulberry32 — 32-битный генератор, период 2^32.
 *
 * Выбран не за качество, а за свойства, которые здесь важнее: одно целое
 * состояние, воспроизводимость до бита и стоимость в несколько операций.
 * Для честности статистики выборки нам довольно равномерности на длине
 * одного прогона, а её mulberry32 даёт с запасом.
 */
export function mulberry32(seed: number): Random {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}

/**
 * Выполнить `fn` с детерминированным потоком случайности от `seed`.
 *
 * ## Почему не подменой глобали, как раньше
 *
 * До версии 1.1.737 пакет звал `Math.random()` напрямую, и подмена глобали
 * была единственным способом им управлять. Теперь у него свой источник
 * случайности, и он захватывает `Math.random` в замыкание ПРИ ЗАГРУЗКЕ
 * модуля — наша подмена, сделанная позже, на него больше не действует.
 *
 * Обнаружилось это не рассуждением, а тестом воспроизводимости: три прогона
 * с одним зерном дали 57.0, 58.3 и 52.3 процента побед. Проверка, которая
 * выглядела формальностью, поймала молчаливую потерю управления случайностью.
 *
 * Пакетный `withRng` подменяет и свой источник, и `Math.random` — прямые
 * вызовы внутри симулятора тоже накрыты. Восстановление у него в `finally`.
 */
export function withSeededRandom<T>(seed: number, fn: () => T): T {
  return withRng(createSeededRng(seed), fn);
}
