/**
 * Управляемая случайность для сравнения расстановок.
 *
 * Зачем это нужно. Симулятор оценивает расстановку методом Монте-Карло, и при
 * 300 симуляциях стандартная ошибка доли около 3 п.п. Разница между хорошей
 * и отличной расстановкой часто 1–3 п.п. Если оценить тысячи кандидатов
 * независимыми прогонами и взять максимум, победит не лучшая расстановка,
 * а самая удачливая: максимум из тысячи зашумлённых оценок смещён вверх на
 * несколько стандартных ошибок, и смещение это больше самого сигнала.
 *
 * Лекарство — общие случайные числа: все кандидаты играются против одной
 * и той же последовательности случайностей. Тогда разница оценок перестаёт
 * зависеть от того, кому больше повезло с бросками, и сравнение становится
 * парным. Замеры выигрыша — в docs/position.md.
 *
 * Почему подменой глобали. Пакет `@firestone-hs/simulate-bgs-battle` зовёт
 * `Math.random()` напрямую в двадцати с лишним файлах и не принимает ни зерна,
 * ни источника случайности. Единственная точка, через которую можно управлять
 * его случайностью извне, — сама глобаль.
 */

export type Random = () => number;

/**
 * mulberry32 — 32-битный генератор, период 2^32.
 *
 * Выбран не за качество, а за свойства, которые здесь важнее: одно целое
 * состояние, воспроизводимость до бита и стоимость в несколько операций.
 * Для честности статистики выборки нам довольно равномерности на длине
 * одного прогона, а её mulberry32 даёт с запасом.
 */
export function mulberry32(seed: number): Random {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}

/**
 * Выполнить `fn`, подменив `Math.random` на детерминированный поток от `seed`.
 *
 * Только для синхронного кода: подмена действует на весь процесс, поэтому всё,
 * что успеет выполниться параллельно, получит те же числа. Симулятор синхронен,
 * а больше эту функцию звать неоткуда.
 *
 * Восстановление идёт через `finally` — исключение внутри симулятора не должно
 * оставлять процесс с зафиксированной случайностью.
 */
export function withSeededRandom<T>(seed: number, fn: () => T): T {
  const original = Math.random;
  Math.random = mulberry32(seed);
  try {
    return fn();
  } finally {
    Math.random = original;
  }
}
