/**
 * Правила таверны — данными, не кодом.
 *
 * ТЗ требует, чтобы конфигурация правил лежала таблицами, а не была вшита
 * в логику. Причина понятна на второй неделе: балансные патчи Hearthstone
 * выходят раз в месяц, тайминги подъёма и ценность племён от них ползут,
 * и менять это должно быть правкой числа, а не поиском по коду.
 *
 * Про происхождение чисел — честно и по пунктам:
 *
 *  - **цены** прочитаны из лога и проверены на фикстурах;
 *  - **тайминги подъёма** — общепринятая кривая сообщества, сверенная с тем,
 *    как играл человек в фикстурах. Это не замер и не оптимум, а отправная
 *    точка, которую видно и легко подвинуть;
 *  - **веса ценности миньона** подобраны так, чтобы порядок предпочтений был
 *    осмысленным, а не так, чтобы совпасть с чьей-то статистикой. Проверка
 *    у нас другая и лучше любых весов: симулятор считает, чем покупка
 *    оборачивается в бою (`docs/tavern.md`).
 */

export interface LevelTiming {
  /** С какого хода эта строка действует. */
  readonly fromTurn: number;
  /** Какой тир к этому ходу хочется иметь. */
  readonly tier: number;
}

export interface TavernRules {
  /**
   * Сколько стоит купить миньона.
   *
   * Правило игры, а не факт лога: именованного тега с ценой покупки
   * в фикстурах нет, у миньонов магазина тега `COST` не оказалось вовсе.
   * Герои и предметы цену меняют — в part3 виден `BACON_REDUCE_BUY_COST`
   * и `BACON_SHOW_OVERRIDEN_MINION_COST`, — но разобрать их мы пока не умеем,
   * и советник этого не скрывает.
   */
  readonly minionCost: number;
  /** Обновление витрины. Прочитано из кнопки `TB_BaconShop_8p_Reroll_Button`: 1. */
  readonly rerollCost: number;
  /** Мест на борде. */
  readonly boardSize: number;

  /**
   * Сколько миньонов показывает витрина на каждом тире (индекс — тир).
   *
   * Тиры 1–5 замерены по шести фикстурам: максимум размера витрины в точках
   * решения — 3/4/4/5/5. Тир 6 в данных не встретился, значение 6 — правило
   * игры, а не замер. Рост на чётных тирах — отдельная причина подниматься,
   * и совет подъёма говорит об этом вслух.
   */
  readonly shopSizeByTier: readonly number[];

  /**
   * К какому тиру стремиться на каком ходу.
   *
   * Кривая сообщества, сверенная с фикстурами: в part3 человек шёл
   * т2 на 3-м ходу, т3 на 5-м, т4 на 7-м — почти ровно по этой таблице;
   * в part2 он играл медленнее и занял место хуже.
   */
  readonly levelling: readonly LevelTiming[];
  /**
   * Ниже этого здоровья подъём таверны не советуется.
   *
   * Смысл не в самом числе, а в том, что оно есть: подъём — это ход без
   * покупки, то есть заведомо слабый бой. На полном здоровье такой размен
   * окупается, на остатках он и есть проигрыш партии.
   */
  readonly levellingHpFloor: number;
  /**
   * Насколько отставание от таблицы усиливает желание подняться.
   * За каждый тир отставания.
   */
  readonly levellingUrgencyPerTier: number;

  /** Веса ценности миньона при покупке. */
  readonly value: {
    /** За каждый тир миньона. */
    readonly perTechLevel: number;
    /** За каждую единицу суммы атаки и здоровья. */
    readonly perStatPoint: number;
    /** За каждого своего миньона того же племени. */
    readonly perTribeMate: number;
    /** Золотой. */
    readonly golden: number;
    /** Ключевые слова. */
    readonly taunt: number;
    readonly divineShield: number;
    readonly poisonous: number;
    readonly windfury: number;
    readonly reborn: number;
    /**
     * Экономический эффект, распознанный по тексту карты.
     *
     * Возврат при продаже или золото — это будущая ценность, которой
     * в статах не видно: River Skipper 1/1 по статам мусор, а по факту
     * возвращает миньона при продаже. Вес НЕ проверяется сверкой с ближайшим
     * боем — экономика окупается через ходы, и это сказано в docs/tavern.md.
     */
    readonly economy: number;
    /**
     * За каждого своего миньона племени, которое карта называет СЛОВАМИ
     * в тексте, не входя в него сама.
     *
     * Случай part9, ход 19: Kangor's Apprentice 3/6 — без племени, тир 5,
     * текст «Summon plain copies of your first 2 Mechs that died». По статам
     * и тиру она слабейшая на борде из мехов, и советник предложил продать
     * её ради Turbo Hogrider — свинобраза, чужого этой композиции. Связь
     * с племенем написана в опубликованном тексте карты, как у тринкетов,
     * — это данные, а не выдуманная таблица ключевых карт.
     *
     * Вес ниже perTribeMate: упоминание слабее принадлежности — племенные
     * баффы на такого миньона не действуют.
     */
    readonly perTextTribeMate: number;
  };

  /**
   * Признаки экономического эффекта в тексте карты.
   *
   * Источники шаблонов — реальные тексты пула: «When you sell this, get …»
   * (River Skipper, Sellemental, Patient Scout), «gain N Gold» / «Tavern
   * Coin» (Accord-o-Tron, Shell Collector). Это данные из опубликованного
   * текста, не выдуманная таблица.
   */
  readonly economyTextWords: readonly string[];

  /**
   * Сколько добавляет каждая уже имеющаяся копия карты.
   *
   * Индекс — число копий на борде и в руке. Две копии означают, что покупка
   * собирает тройку: миньон становится золотым и даёт открытие карты тиром
   * выше. Это самая сильная покупка в игре, и вес это отражает.
   */
  readonly copiesBonus: readonly number[];

  /**
   * Слово, которым текст карты называет племя. Ключ — имя племени в поле
   * `races` снапшота Firestone.
   *
   * У тринкетов в снапшоте нет поля `races` — племя написано словами
   * в тексте карты («give a friendly Dragon +X/+Y»). Это данные из
   * опубликованного текста, а не выдуманная таблица ценности: совет по
   * тринкетам ранжирует их по числу своих миньонов упомянутых племён
   * и честно отказывается оценивать эффекты вне племён. Той же таблицей
   * ценность миньона учитывает племя, названное в тексте карты
   * (`perTextTribeMate`).
   *
   * Ключи обязаны совпадать со строками `races` снапшота: там племя
   * механизмов называется `MECH`, и ключ MECHANICAL не совпадал ни с чем —
   * на part9 при пяти мехах на борде тринкет про мехов получал «своих таких
   * нет». Все ключи сверены со списком рас пула:
   * ALL, BEAST, DEMON, DRAGON, ELEMENTAL, MECH, MURLOC, NAGA, PIRATE,
   * QUILBOAR, UNDEAD.
   */
  readonly tribeTextWords: Readonly<Record<string, string>>;

  /**
   * Признаки «сила даёт миньона» в тексте силы героя.
   *
   * Скаббс («I Spy», за 2: «Discover a plain copy of a minion from your next
   * opponent's warband») — типовой случай: сила за золото приносит существо,
   * и это выгоднее третьей покупки. Про силы вне этих шаблонов — урон, баффы —
   * совет не берётся судить, как и с тринкетами.
   *
   * Порядок слов в шаблоне не гарантирован: у Зиреллы («See the Light»,
   * part9: «Choose a minion in the Tavern. Set its stats to 2 and add it
   * to your hand») объект глагола — местоимение, «minion» стоит в другом
   * предложении. Шаблоны «глагол…minion» такую силу не видели, и советник
   * молчал при золоте ровно на неё — на что игрок и указал.
   */
  readonly heroPowerMinionWords: readonly string[];

  /**
   * Очков ценности в одном золотом.
   *
   * Курс выводится из самих правил, а не выдуман: покупка за 3 золота даёт
   * миньона на ~9 очков к середине партии, то есть золото ≈ 3 очка. Нужен,
   * когда действия стоят по-разному: сила героя за 2 против покупки за 3.
   */
  readonly goldPointValue: number;

  /**
   * Ценность нажатия тёмного дара.
   *
   * Дар — усиление миньона, которого не купить в витрине. Вес задан данными
   * и, как у экономики, не проверяется ближайшим боем: дар выбирается
   * из трёх позже, и что выпадет — неизвестно.
   */
  readonly darkGift: {
    readonly value: number;
  };

  /**
   * Порог «покупать нечего» для обновления витрины, ОТНОСИТЕЛЬНО тира.
   *
   * Порог = perTechLevel × тир + этот запас. Прежний плоский порог (6) был
   * калиброван под ранние тиры и к пятому переставал срабатывать вовсе:
   * любой миньон пятого тира стоит больше шести очков уже одним тиром,
   * и реролл не советовался никогда — на что игрок и указал.
   */
  readonly rerollMarginOverTier: number;
  /**
   * Заморозка.
   *
   * Незамороженная витрина обновляется в начале хода БЕСПЛАТНО, поэтому
   * заморозка — это не «сохранить хорошее», а «отказаться от нового даром».
   * Голые статы и тир такого отказа не окупают: свежая витрина в среднем
   * не хуже. Окупает только то, чего свежая витрина не даст, — копия под
   * тройку или миньон нужного племени.
   */
  readonly freeze: {
    /** Морозить только кандидата не дешевле этого — по общей шкале ценности. */
    readonly minValue: number;
    /** Либо копия под тройку, либо своих того же племени не меньше стольких. */
    readonly minTribeMates: number;
  };
  /**
   * Насколько лучший кандидат из магазина должен превосходить худшего своего,
   * чтобы советовать продажу ради места.
   */
  readonly sellMargin: number;
}

