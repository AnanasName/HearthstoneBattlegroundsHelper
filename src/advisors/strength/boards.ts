/**
 * Эталонное поле: борды, которые ЧУЖИЕ игроки выставляли на каждом ходу.
 *
 * ## Зачем
 *
 * Вопрос игрока (06.09): «хочу, чтобы софт писал, сильный мой стол для
 * данного хода или нет, — чтобы было понятно, стоит усиливаться или лучше
 * улучшить таверну / купить экономическую карту». Своего борда для ответа
 * мало: «38 статов» — это сильно на пятом ходу таверны и смешно на девятом.
 * Нужна НОРМА хода, и норму эту нельзя выдумывать — её надо взять
 * из наблюдений.
 *
 * ## Откуда борды
 *
 * Из ФАКТИЧЕСКИХ боёв наших партий (`readBattleEpisodes`): каждый бой
 * показывает борд соперника целиком, и ход этого боя известен. Это чужие
 * борды — восьмерых живых игроков нашего рейтинга, — а не наши, поэтому
 * второй контур петли (docs/ml.md: «партия по подсказкам — не как играют
 * люди») тут не задет: советник на эти борды не влиял никак.
 *
 * Ход хранится в ходах ТАВЕРНЫ (`tavernTurnOf`), как `trinketOfferTurns`
 * и `remainingTavernTurns`: числа замерены у нас и в нашей нумерации
 * (урок part20 — чужие таблицы переводятся, свои нет).
 *
 * ## Чего в снапшоте нет
 *
 * Героя соперника нет: в логе его борд виден, а карточка героя на момент
 * боя — нет (то же ограничение, что у `toBattleInfo`, где подставляется
 * заглушка). Тринкеты есть — их игра пишет тегами на героях.
 *
 * ## Почему это ДАННЫЕ, а не расчёт при старте
 *
 * Ровно по той же причине, что веса прогноза места (`data/ml/`): логи
 * фикстур есть у нас и нет у исполнителя. Модуль, собирающий поле
 * из логов при запуске, работал бы на этой машине и молча молчал бы
 * у всех прочих. Поэтому снапшот — файл, обновляемый явной командой
 * (`npm run field:fit`), закоммиченный и уезжающий в сборку через
 * `extraResources`.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { APP_PATHS } from '../../app/paths.js';
import type { Deity, Minion } from '../../state/types.js';

export const FIELD_BOARDS_PATH = join(APP_PATHS.dataDir, 'field', 'boards.json');

/** Один чужой борд, снятый в бою на известном ходу таверны. */
export interface FieldBoard {
  /** Ход ТАВЕРНЫ, на котором этот борд вышел в бой. */
  readonly tavernTurn: number;
  /** Партия-источник: нужна замеру, чтобы не мерить партию об неё саму. */
  readonly part: number;
  /** Ход партии — вместе с `part` даёт бою имя, по которому его можно найти. */
  readonly turn: number;
  readonly board: readonly Minion[];
  /** Тринкеты владельца борда, как dbfId из лога. */
  readonly trinketDbfIds: readonly number[];
  /**
   * Божество владельца борда в этом бою (D287) — или `null`. С пулом 22.09
   * сигил Божества есть у КАЖДОГО игрока (part68–part77: 138 боёв из 138),
   * а живой счёт силы отдаёт симулятору наше Божество: поле без Божеств
   * соперников — односторонняя точность (D205, D304). Нет поля — борд
   * собран до 25.09.
   */
  readonly deity?: Deity | null;
}

export interface FieldSnapshot {
  /** Когда собран — снапшот устаревает с патчем, как и снапшот карт. */
  readonly builtAt: string;
  /**
   * Отпечаток пула снапшота карт, на котором собрано поле
   * (`poolFingerprint`, D304). Нет его — поле собрано до 25.09, и пул его
   * неизвестен: с партией оно не сверяется.
   */
  readonly pool?: string;
  /** Партии-источники: фикстуры нынешнего пула (`fit.ts`, `offPoolShopCards`). */
  readonly parts: readonly number[];
  readonly boards: readonly FieldBoard[];
  /** Цена поражения по ходам таверны — см. `FieldDamage`. */
  readonly damage: readonly FieldDamage[];
}

/**
 * Снапшот с диска или `null`, если его нет.
 *
 * `null` — обычное состояние у свежей установки без снапшота, и отвечать
 * на него надо молчанием блока, а не выдуманным полем: поле из ноля бордов
 * дало бы «вы сильнее 0 из 0 соперников».
 */
export function loadFieldBoards(path: string = FIELD_BOARDS_PATH): FieldSnapshot | null {
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, 'utf8')) as FieldSnapshot;
}

/**
 * Борды одного хода таверны.
 *
 * Отдельной функцией, а не фильтром на месте, потому что читателей у неё
 * двое — живой счёт силы и замер калибровки, — и «какие борды считаются
 * полем этого хода» обязано быть у них одним: разъехалось бы молча.
 *
 * ## `excludePart` в ЛЮБОМ замере по фикстурам обязателен
 *
 * В живой игре его передавать неоткуда и не нужно: партия идёт сейчас,
 * и в поле её бордов нет. А вот замер, который читает фикстуру и сверяется
 * с её же боями, без этого аргумента спрашивает ответ у ответа: борд
 * фактического соперника лежит в ТОМ ЖЕ логе и попадает в поле, против
 * которого мы этот бой и оцениваем.
 *
 * Класс ошибки в проекте уже стоил замера: сверка покупок против последнего
 * увиденного борда соперника давала разгром 100:0 и тождественно нулевой
 * разброс между кандидатами (CLAUDE.md, «Сверять покупки против последнего
 * увиденного борда нельзя»). Опасна она тем, что не падает и не выглядит
 * подозрительно — просто числа получаются слишком хорошими.
 */
export function boardsOfTurn(
  snapshot: FieldSnapshot,
  tavernTurn: number,
  excludePart: number | null = null,
): readonly FieldBoard[] {
  return snapshot.boards.filter(
    (b) =>
      b.tavernTurn === tavernTurn &&
      b.board.length > 0 &&
      (excludePart === null || b.part !== excludePart),
  );
}

/**
 * Во что обходится ПОРАЖЕНИЕ на этом ходу — замер по тем же боям.
 *
 * Второе число блока, и оно тут не для полноты картины. Вопрос игрока был
 * не «силён ли я вообще», а «стоит ли усиливаться или можно улучшить
 * таверну»; на него одной силой не ответить, потому что цена проигранного
 * боя за партию меняется на порядок: на первом ходу таверны поражение
 * стоит 2 очка здоровья, на девятом — тринадцать. Слабый борд при полном
 * запасе здоровья и слабый борд на двадцати очках — разные положения,
 * и различает их только это число.
 *
 * Считается по фактическому `damageTaken` ПРОИГРАННЫХ боёв: у выигранных
 * и ничейных урон нулевой, и подмешивать их значило бы отвечать
 * на «сколько в среднем теряют», а не на «сколько потеряю, если проиграю».
 */
export interface FieldDamage {
  readonly tavernTurn: number;
  /** Средний урон в проигранных боях этого хода. */
  readonly mean: number;
  /** По скольким проигранным боям посчитано. */
  readonly losses: number;
}
