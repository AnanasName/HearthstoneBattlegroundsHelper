/**
 * Какие билды игры считаются ОДНОЙ игрой.
 *
 * Датасет фазы 6 и сверки отбирают партии по номеру билда: пул карт,
 * тиры и правила меняются с патчем, и учиться на прошлом патче — учиться
 * другой игре. Замерено: после патча 246003 → 248348 расхождение
 * калибровки выросло с 3.9 до 9.0 п.п. без единой правки кода.
 *
 * Но не всякий новый номер билда — новый патч. Бывает баланс и багфиксы:
 * карты те же, тиры те же, меняются числа отдельных карт. Выбрасывать
 * из-за такого весь накопленный датасет — терять данные на формальности.
 *
 * Поэтому здесь ТАБЛИЦА, а не правило «новейший билд». Каждая строка —
 * группа билдов, объявленных одной игрой, с датой и основанием. Пополнять
 * её можно только по факту, а не по удобству: основание «пул карт
 * не менялся» проверяется двумя способами — словами игрока, который
 * читал патчноут, и счётом незнакомых карт в его партии (тот же сигнал,
 * что у предупреждения о свежести снапшота, `src/live/freshness.ts`).
 *
 * Цена допущения названа вслух: баланс МЕНЯЕТ силу отдельных карт, и наши
 * веса ценности покупки этого не знают. Если после объединения замеры
 * начнут вести себя странно, первый подозреваемый — эта таблица.
 */

