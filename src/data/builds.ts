/** Билды, играющие в ту же игру, что и указанный. Сам билд всегда входит. */
export function compatibleBuilds(build: number | null): ReadonlySet<number> {
  if (build === null) return new Set();
  const group = BUILD_GROUPS.find((g) => g.includes(build));
  return new Set(group ?? [build]);
}

/** Одна ли это игра: билд записи против билда, по которому идёт отбор. */
export function sameGameBuild(recordBuild: number | null, currentBuild: number | null): boolean {
  if (recordBuild === null || currentBuild === null) return recordBuild === currentBuild;
  return compatibleBuilds(currentBuild).has(recordBuild);
}
