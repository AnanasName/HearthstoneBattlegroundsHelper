/**
 * Обрезка снапшота карт до того, что кто-то читает.
 *
 * Зачем. Снапшот с сервера Firestone весит 39.8 МБ и лежит у нас как скачан:
 * массив из 36 023 карт, записанный с отступами в четыре пробела. Его читает
 * КАЖДЫЙ процесс, которому нужен симулятор или справочник, — а таких процессов
 * стало много: батарея раскладывает партии по 156 задачам, а советник
 * расстановки собирается считать несколькими воркерами, и снапшот тогда
 * умножается на их число.
 *
 * Откуда берётся выигрыш. Два независимых источника, оба без потери смысла:
 *
 *   - **Отступы.** Источник отдаёт JSON человекочитаемым. Та же структура
 *     без пробелов — 21.4 МБ вместо 39.8.
 *   - **Поля, которые не читает никто.** Их двадцать, и в них 11.5 МБ
 *     из оставшихся 21.4. Больше половины — `audio2` (10.1 МБ): ссылки
 *     на звуковые файлы клиента, которых у нас нет и быть не может.
 *
 * Итого около 10 МБ вместо 39.8.
 *
 * Почему список именно такой. Он не придуман, а посчитан: имя каждого из 56
 * полей снапшота искалось в ИСПОЛНЯЕМОМ коде — 945 файлов `.js` у пакетов
 * `@firestone-hs` (там лежит скомпилированный симулятор) и наши `.ts`.
 * Объявление поля в `.d.ts` чтением не считается: там оно только описано.
 * Динамического доступа вида `card[имя]` у firestone нет вовсе, а у нас он
 * есть только по объектам миньона и флагам, не по сырым картам снапшота, —
 * иначе поиск по именам ничего бы не доказывал.
 *
 * Почему список проверяется тестом. Обновление пакета симулятора может начать
 * читать поле, которое сегодня не читает никто, и тогда обрезка станет тихой
 * потерей данных — тот самый случай «не падение, а неверный результат».
 * `test/data/cardsSnapshot.test.ts` пересчитывает список при каждом прогоне
 * и падает, если выброшенное поле кому-то понадобилось.
 */

/**
 * Поля снапшота, которые не читает ни симулятор, ни наш код.
 *
 * Рядом с каждым — чем оно было в игре, чтобы список читался, а не принимался
 * на веру.
 */
export const DROPPED_FIELDS: readonly string[] = [
  'audio2', // ссылки на звуки клиента — 10.1 МБ, больше половины всей обрезки
  'flavor', // шуточный текст карты
  'artist', // имя художника
  'collectible', // собираемость в коллекционном режиме
  'otherTags',
  'hideStats', // прятать ли статы в интерфейсе
  'additionalCosts',
  'durability', // прочность оружия, в Battlegrounds оружия нет
  'questRewardDbfId',
  'isTreant',
  'touristFor',
  // Наёмники — отдельный режим игры, к Battlegrounds отношения не имеющий.
  'mercenaryEquipment',
  'mercenaryAbilityCooldown',
  'mercenaryRole',
  'mercenaryPassiveAbility',
  'mercenaryAbility',
  // Косметика героев и карт.
  'battlegroundsHeroSkin',
  'availableAsSignature',
  'availableAsDiamond',
  'battlegroundsHero', // ПРИЗНАК героя; ссылку на родителя (`battlegroundsHeroParentDbfId`) читают, и она остаётся
];

const DROPPED = new Set(DROPPED_FIELDS);

/**
 * Убрать неиспользуемые поля, сохранив порядок остальных.
 *
 * Порядок важен не для машины, а для человека: снапшот лежит в git, и его
 * обновление читают глазами через diff. Перетасованные ключи превратили бы
 * любое обновление в сплошное красное полотно.
 */
export function trimSnapshot(cards: readonly unknown[]): unknown[] {
  return cards.map((card) => {
    if (card === null || typeof card !== 'object' || Array.isArray(card)) return card;
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(card as Record<string, unknown>)) {
      if (!DROPPED.has(key)) out[key] = value;
    }
    return out;
  });
}

/** Снапшот в том виде, в каком он ложится на диск: обрезанный и без отступов. */
export function serializeSnapshot(cards: readonly unknown[]): string {
  return JSON.stringify(trimSnapshot(cards));
}
