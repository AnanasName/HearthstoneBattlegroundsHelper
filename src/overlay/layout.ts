/**
 * Отношение ширины окна к высоте.
 *
 * Нужно потому, что длины замерены высотой, а `Rect.x`/`Rect.w` наружу идут
 * долями ширины: разметке удобны проценты, и пересчёт лучше сделать один раз
 * здесь, чем в каждом месте, которое рисует.
 */
export type Aspect = number;

function rectAround(cx: number, cy: number, w: number, h: number, aspect: Aspect): Rect {
  const width = w / aspect;
  return { x: cx - width / 2, y: cy - h / 2, w: width, h };
}

/**
 * Прямоугольник слота в ряду; `null` — слота нет.
 *
 * Пустой ряд и выход за его пределы возвращают `null`, а не нулевой
 * прямоугольник: «карты там нет» и «карта размером ноль» — разные вещи,
 * и вторая нарисовалась бы точкой в углу стола.
 */
export function slotRect(
  row: SlotRow,
  index: number,
  count: number,
  aspect: Aspect,
): Rect | null {
  if (count <= 0 || index < 0 || index >= count) return null;
  const model = ROWS[row];
  const cx = CENTER_X + ((index - (count - 1) / 2) * model.step) / aspect;
  return rectAround(cx, model.y, model.w, model.h, aspect);
}

/** Прямоугольник кнопки таверны. */
export function buttonRect(button: TavernButton, aspect: Aspect): Rect {
  const model = BUTTONS[button];
  return rectAround(CENTER_X + model.dx / aspect, model.y, model.w, model.h, aspect);
}

/**
 * Прямоугольник в пикселях CSS: где на ОКНЕ лежит экран игры.
 *
 * Доли `Rect` считаются от СТОЛА, а стол — это весь экран. Пока окно
 * оверлея совпадало с экраном, одно от другого не отличалось, и слой меток
 * жил на `inset: 0`.
 */
export interface PixelBox {
  readonly left: number;
  readonly top: number;
  readonly width: number;
  readonly height: number;
}

/** Прямоугольник экрана или окна так, как их отдаёт Electron: DIP, начало — угол экрана. */
export interface Bounds {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

/**
 * Где на окне лежит экран игры — в пикселях CSS от угла содержимого окна.
 *
 * ## Зачем это вообще понадобилось
 *
 * Окно просит себе `bounds` экрана (см. `window.ts`), но ПОЛУЧАЕТ не всегда
 * его: Windows ужимает обычное окно до РАБОЧЕЙ ОБЛАСТИ — экрана без панели
 * задач. Проверить это можно было только кадром живой игры, и кадр пришёл
 * (part46, жалоба «обводка силы героя немного выше»): на экране 2560×1600
 * при масштабе 150 % рабочая область — 1019 DIP вместо 1067, то есть окно
 * ниже экрана на 48 DIP (72 пикселя устройства).
 *
 * Дальше арифметика сама: доля 0.7749 от 1528 пикселей — это 1184, а от
 * 1600 — 1240, и кольцо силы героя село на 48 пикселей выше кнопки. Замер
 * по кадру дал ровно это, тремя метками сразу: обновление витрины 277
 * (модель обещает 281 при рабочей области и 294 при экране), номера
 * расстановки 725 (722 / 756), сила героя 1185 (1184 / 1240). Прямая через
 * эти три точки даёт высоту 1537 ± 17 при рабочей области 1528 — то есть
 * промах РОС сверху вниз, и потому первым его увидели у самой нижней метки
 * на экране, а не у витрины.
 *
 * ## Почему считается так, а не «сделать окно во весь экран»
 *
 * Заставить Windows отдать окно во весь экран можно, но проверить у нас
 * нечем: Electron тут не запускается, и правка «должна помочь» уехала бы
 * к игроку непроверенной. Здесь же утверждение слабее и потому надёжнее:
 * КАКИМ БЫ окно ни вышло, метки лежат на экране, потому что считаются от
 * экрана и сдвигаются на разницу углов. Панель задач при этом ничего
 * не отнимает: самая нижняя метка (сила героя) стоит на 0.836 высоты,
 * то есть внутри рабочей области с запасом.
 *
 * Обе величины — в DIP, и это одно и то же, что пиксели CSS: Electron меряет
 * окна в DIP, а Chromium в этих же единицах рисует. Масштаб экрана (у игрока
 * 150 %) сокращается и в счёт не входит вовсе.
 */
export function stageBox(display: Bounds, content: Bounds): PixelBox {
  return {
    left: display.x - content.x,
    top: display.y - content.y,
    width: display.width,
    height: display.height,
  };
}
