/**
 * Где на экране лежат карты игры — геометрией, а не зрением.
 *
 * Компьютерного зрения в проекте нет и не будет: лог говорит «третий миньон
 * витрины», а нарисовать кольцо надо в пикселях. Мост между этими двумя
 * мирами — тут, и он держится на одном наблюдении: Hearthstone раскладывает
 * ряд АРИФМЕТИКОЙ от числа карт. Ряд центрируется по столу, шаг между
 * слотами постоянный, размеры слота тоже.
 *
 * ## Как получены числа
 *
 * Замерены по настоящим кадрам из `data/screenshots/` (2553×1599 и 2559×1599).
 * Калибровка снята с кадра, где в витрине ПЯТЬ карт, а на борде СЕМЬ, и без
 * единой правки проверена на кадре с ТРЕМЯ и ЧЕТЫРЬМЯ — кольца сели на карты.
 * Это и есть доказательство, что раскладка считается, а не подбирается:
 * модель, подогнанная под один состав, не легла бы на другой.
 *
 * Шаг ряда и центр стола проверены не глазом, а ЯКОРЕМ: розовый медальон
 * тира над картой витрины ловится маской по цвету, и его центры на кадре
 * дают шаг 207.06 пикселя (модель — 0.1295 × 1599 = 207.06) при центре ряда
 * 0.4988 против нашего 0.498. Тот же якорь показал и ошибку вертикали,
 * прожившую до part42: медальон стоит НАД картой, и слот витрины, начинаясь
 * на его верхушке, был на 40 пикселей выше самой карты.
 *
 * Все длины — в долях ВЫСОТЫ окна, и это не прихоть: Hearthstone масштабирует
 * стол по высоте и центрирует по ширине, поэтому доля высоты переносится между
 * разрешениями, а доля ширины — нет.
 *
 * ## Чего эти числа НЕ покрывают, и это надо знать до того, как верить
 *
 * - Оба кадра сняты на ОДНОЙ машине в 16:10. Перенос на 16:9 — гипотеза,
 *   а не замер: доля высоты обязана перенестись, но проверить это можно
 *   только кадром с другого экрана.
 * - Ряд лавки аксессуаров (`trinket`) снят ГЛАЗОМ с присланного кадра, а не
 *   пиксельным замером: этого кадра в `data/screenshots/` нет. Числа стоят
 *   отдельно и подписаны у себя, и цену такого замера уже заплатили: первый
 *   глазомер занизил шаг на четверть, кольцо уехало на полкарты, и увидел
 *   это игрок, а не тест.
 * - Сила героя НЕ опознана. Кружок на её предполагаемом месте в раннем кадре
 *   бронзовый с замком, а в позднем фиолетовый — это слот тринкета,
 *   открывающийся на 11-м ходу, а не сила. Выдумывать координату нельзя,
 *   поэтому её здесь нет вовсе.
 * - Рука не мерена: карты в руке лежат веером с поворотом, одной формулой
 *   центрированного ряда это не описывается.
 *
 * Действие, объект которого разместить негде, меткой не помечается — оно
 * остаётся в панели. Это и есть причина, по которой панель не исчезает.
 */

/** Прямоугольник в долях окна: `x`/`w` — от ширины, `y`/`h` — от высоты. */
export interface Rect {
  readonly x: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}

/**
 * Ряд карт, который игра центрирует по столу.
 *
 * `trinket` — не стол, а МОДАЛЬНЫЙ экран лавки аксессуаров, и стоит он в этом
 * же списке потому, что раскладывается той же арифметикой: ряд по центру,
 * шаг постоянный. Точность у него другая, и это сказано у самих чисел.
 */
export type SlotRow = 'shop' | 'board' | 'trinket';

/** Кнопки таверны, чьё положение замерено. */
export type TavernButton = 'levelUp' | 'refresh' | 'freeze';

interface RowModel {
  /** Вертикаль центра ряда, доля высоты. */
  readonly y: number;
  /** Шаг между центрами слотов, доля высоты. */
  readonly step: number;
  /** Размер слота, доли высоты. */
  readonly w: number;
  readonly h: number;
}

interface ButtonModel {
  /** Смещение центра от центра стола, доля ВЫСОТЫ (не ширины). */
  readonly dx: number;
  readonly y: number;
  readonly w: number;
  readonly h: number;
}

/**
 * Центр стола по горизонтали — доля ШИРИНЫ.
 *
 * Единственная величина, меряемая шириной: вокруг неё центрируется всё
 * остальное, а само оно стоит посреди окна.
 */
const CENTER_X = 0.498;

const ROWS: Readonly<Record<SlotRow, RowModel>> = {
  // Витрина. Числа перемерены 05.09 по кадрам `data/screenshots/` после
  // жалобы игрока «обводка высоковата» (part42): прежний слот
  // (`y: 0.366, h: 0.152`) захватывал МЕДАЛЬОН ТИРА — розовый значок
  // со звёздами, который стоит НАД картой и картой не является. Медальон
  // держится на 459..508 пикселях на всех пяти кадрах, а рамка карты идёт
  // с 503 до 704, — то есть слот был на 40 пикселей выше карты сверху
  // и точен снизу. Ширина взята бордовой (карты одного размера, шаг у обоих
  // рядов один); по вертикали витрина ниже борда, потому что стол наклонён
  // и дальний ряд сжат перспективой.
  shop: { y: 0.377, step: 0.1295, w: 0.106, h: 0.126 },
  board: { y: 0.545, step: 0.1295, w: 0.106, h: 0.145 },
  // Лавка аксессуаров. Числа по-прежнему сняты ГЛАЗОМ — кадра лавки
  // в `data/screenshots/` нет, оба присланных пришли картинкой в переписку,
  // — и первый глазомер (part41) промахнулся: шаг 0.204 при настоящем 0.251
  // уводил кольцо первого варианта на ПОЛКАРТЫ вправо, на границу с соседом
  // (жалоба игрока, part42: «обводка trinkets съехала»). Числа сходятся
  // между собой: карта шириной 0.238 при шаге 0.251 оставляет промежуток
  // в 22 пикселя — ровно те узкие полоски со стрелками, что видны на кадре,
  // — а ряд из четырёх занимает 62% ширины окна, как на кадре и стоит.
  // Вертикаль первого замера подтвердилась и не тронута.
  trinket: { y: 0.454, step: 0.251, w: 0.238, h: 0.284 },
};

const BUTTONS: Readonly<Record<TavernButton, ButtonModel>> = {
  levelUp: { dx: -0.156, y: 0.184, w: 0.072, h: 0.1 },
  refresh: { dx: 0.152, y: 0.184, w: 0.072, h: 0.1 },
  freeze: { dx: 0.255, y: 0.184, w: 0.072, h: 0.1 },
};

/**
 * Отношение ширины окна к высоте.
 *
 * Нужно потому, что длины замерены высотой, а `Rect.x`/`Rect.w` наружу идут
 * долями ширины: разметке удобны проценты, и пересчёт лучше сделать один раз
 * здесь, чем в каждом месте, которое рисует.
 */
export type Aspect = number;

function rectAround(cx: number, cy: number, w: number, h: number, aspect: Aspect): Rect {
  const width = w / aspect;
  return { x: cx - width / 2, y: cy - h / 2, w: width, h };
}

/**
 * Прямоугольник слота в ряду; `null` — слота нет.
 *
 * Пустой ряд и выход за его пределы возвращают `null`, а не нулевой
 * прямоугольник: «карты там нет» и «карта размером ноль» — разные вещи,
 * и вторая нарисовалась бы точкой в углу стола.
 */
export function slotRect(
  row: SlotRow,
  index: number,
  count: number,
  aspect: Aspect,
): Rect | null {
  if (count <= 0 || index < 0 || index >= count) return null;
  const model = ROWS[row];
  const cx = CENTER_X + ((index - (count - 1) / 2) * model.step) / aspect;
  return rectAround(cx, model.y, model.w, model.h, aspect);
}

/** Прямоугольник кнопки таверны. */
export function buttonRect(button: TavernButton, aspect: Aspect): Rect {
  const model = BUTTONS[button];
  return rectAround(CENTER_X + model.dx / aspect, model.y, model.w, model.h, aspect);
}
