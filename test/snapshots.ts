/**
 * Когда снимать состояние при прогоне фикстуры — один ответ на все тесты.
 *
 * ## Зачем фильтр вообще
 *
 * `reducer.snapshot()` стоит девяти проходов по карте сущностей, а событий
 * в партии под двести тысяч: снимать на каждом — это десятки секунд на файл.
 * Поэтому тесты снимают только после строк, которые МОГУТ изменить читаемое
 * селекторами.
 *
 * ## Чем он опасен
 *
 * Фильтр по подстрокам — это утверждение «после остальных строк состояние
 * то же самое», и оно обязано покрывать всё, что читают селекторы. Список
 * жил в каждом тесте своей копией и, разумеется, разъехался: у part17
 * селектор ловит момент условием `!shop.some((m) => m.frozen)`, а строки
 * `tag=FROZEN` его фильтр не пропускал вовсе — снимок мог быть взят ДО
 * заморозки, и тест проверял бы состояние, которого в партии не было.
 * Это не падение, а тихо неверная точка отсчёта: тест зелен, а момент
 * чужой.
 *
 * Поэтому база одна и перечисляет то, из чего состоит вопрос
 * советника: состав зон, золото, тир, цены, номер хода, заморозка витрины
 * и модальный выбор. Дешёвых причин снимать реже нет — все эти метки, кроме
 * зон, встречаются в логе сотнями строк, а не тысячами.
 *
 * ## Чего база НЕ покрывает — и это не забывчивость
 *
 * Здоровье героя (`DAMAGE`/`ARMOR`/`HEALTH`), таблица лобби
 * (`PLAYER_LEADERBOARD_PLACE`, чужой `PLAYER_TECH_LEVEL`) и плейсхолдеры
 * (`TAG_SCRIPT_DATA_NUM_*`) в список НЕ входят, хотя советник их читает:
 * порог подъёма смотрит на hp, ставка на чужой бой — на лобби, усиления —
 * на плейсхолдеры. Их метки идут в логе ТЫСЯЧАМИ строк, и цена снимка
 * вернулась бы целиком. Правило такое: тест, чей селектор ловит момент
 * по этим величинам, передаёт свои метки вторым аргументом — как part22
 * передаёт статы. База отвечает за состав зон, экономику и выбор, а не
 * за всё состояние.
 *
 * Полного единообразия тоже нет и оно не заявляется: part11 остался
 * на своём селекторе (`RESOURCES_USED`/`ZONE` плюс каждое седьмое
 * событие), а тесты part23–part26 фильтра не имеют вовсе — «снимать
 * всегда» строже любого фильтра, и переводить их значило бы ослаблять
 * ради скорости.
 *
 * СТАТЫ вынесены отдельно: `tag=ATK`/`tag=HEALTH` — это ещё 15 тысяч строк
 * на партию (треть сверху), и нужны они только там, где селектор ловит
 * момент по атаке или здоровью. Тест объявляет это сам, а не платит за всех.
 */

/** Метки строк, после которых советник может увидеть другое состояние. */
const ADVISOR_STATE_MARKERS: readonly string[] = [
  // Состав борда, руки и витрины: зона и позиция.
  'ZONE',
  // Золото: остаток — это `RESOURCES` минус `RESOURCES_USED`.
  'RESOURCES',
  // Тир таверны, свой и чужой (`PLAYER_TECH_LEVEL`).
  'TECH_LEVEL',
  // Живые цены: кнопки подъёма и обновления, заклинания, скидки.
  'COST',
  // Номер хода — по нему отбирается сама точка.
  'tag=TURN',
  // Заморозка витрины: её читают и селекторы, и правила заморозки.
  'FROZEN',
  // Модальный выбор: раскопка, тройка, лавка, ставка, смена силы героя.
  'Choice',
  'Entities[',
];

/**
 * Статы миньонов. Передаются вторым аргументом теми тестами, чьи селекторы
 * ловят момент по атаке или здоровью (part22: счетовод в руке на 208/206).
 */
export const MINION_STAT_MARKERS: readonly string[] = ['tag=ATK', 'tag=HEALTH'];

/** Может ли эта строка лога изменить то, что читают селекторы теста. */
export function changesAdvisorState(content: string, extra: readonly string[] = []): boolean {
  return (
    ADVISOR_STATE_MARKERS.some((marker) => content.includes(marker)) ||
    extra.some((marker) => content.includes(marker))
  );
}
